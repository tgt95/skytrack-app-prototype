import { type MissionInsightSample } from './mission-insights-data'
import {
  reportForSample,
  asRecord,
  textValue
} from './mission-insights-report-data'
import { DownloadSimpleIcon } from '@phosphor-icons/react'
import { DetailSection } from './mission-insights-page-sections'
import { Button } from 'skytrack-ui/button'
import { CodeBlockTree } from 'skytrack-ui/code-block-tree'

export function jsonPropertyLines (
  key: string,
  value: unknown,
  hasNext: boolean
) {
  const lines = JSON.stringify({ [key]: value }, null, 2)
    .split(/\r?\n/)
    .slice(1, -1)
  if (hasNext && lines.length)
    lines[lines.length - 1] = `${lines[lines.length - 1]},`
  return lines
}

export function RawJsonTab ({ sample }: { sample: MissionInsightSample }) {
  const report = reportForSample(sample)
  const generator = asRecord(report.generator)
  const source = asRecord(report.source)

  function downloadJson () {
    const blob = new Blob([JSON.stringify(report, null, 2)], {
      type: 'application/json'
    })
    const url = URL.createObjectURL(blob)
    const link = document.createElement('a')
    link.href = url
    link.download = `mission-insights-${sample.key}-sample.json`
    link.click()
    URL.revokeObjectURL(url)
  }

  return (
    <div className='flex min-w-0 flex-col gap-6'>
      <DetailSection
        className='no-border'
        title={
          <>
            <span>Mission Insight report</span>
            <p className='mt-1 text-sm font-normal [font-family:var(--font-family)] text-muted-foreground'>
              Schema {textValue(report.schema_version, 'Not supplied')} ·
              generated by {textValue(generator.name, 'Not supplied')}{' '}
              {textValue(generator.version, '')} · source{' '}
              {textValue(source.label, 'Not supplied')}
            </p>
          </>
        }
      >
        <CodeBlockTree
          className='[&_[data-slot=code-block-title]]:font-mono [&_[data-slot=code-block-title]]:text-sm [&_[data-slot=code-block-title]]:text-muted-foreground'
          value={report}
          // title='Mission Insight report JSON'
          showLineNumbersToggle={false}
          size='default'
          toolbarActions={
            <Button variant='outline' size='sm' onClick={downloadJson}>
              <DownloadSimpleIcon aria-hidden='true' />
              Download
            </Button>
          }
        />
      </DetailSection>
    </div>
  )
}
